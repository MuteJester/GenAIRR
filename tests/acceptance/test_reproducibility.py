"""Same seed, same bytes -- within a run, and across platforms.

GenAIRR's published datasets are other people's ground truth, and the CI matrix
is three operating systems by four Python versions. If the same seed produced
different output on a different platform, every comparison anyone made against
a GenAIRR dataset would be silently platform-dependent. That makes this the
single most important assertion about the product, and it was unwritten: the
golden fixtures existed, the regeneration script named the test that would read
them, and that test had never existed in the history.

Two claims, because they fail for different reasons:

- Determinism, checked here and now: one seed, two runs, identical bytes. This
  catches iteration-order and hash-seed dependence on whatever platform runs it.
- Cross-platform agreement, checked against a committed golden. It can only
  pass on the platform that produced the golden and only bites in CI on the
  others, which is exactly its job.
"""
from __future__ import annotations

import pytest

from tests.support import golden, paths

pytestmark = pytest.mark.composition

#: Shared with the generator so the two cannot disagree about what a fixture is.
FIXTURES = golden.every_fixture()


def _tsv(tmp_path, locus: str, *, n: int, mixed: bool, tag: str = "a") -> str:
    """The TSV export as text, written through the real export path -- that is
    the artifact users actually compare against."""
    out = golden.write_reproducibility_tsv(
        tmp_path / f"{locus}-{n}-{tag}.tsv", locus, n=n, mixed=mixed)
    return out.read_text(encoding="utf-8")


@pytest.mark.parametrize("name,locus,n,mixed", FIXTURES)
def test_one_seed_produces_identical_bytes_twice(name, locus, n, mixed, tmp_path):
    """Determinism on whatever platform this runs on.

    Separate from the golden comparison on purpose: this fails for
    iteration-order or hash-seed dependence, which is a different defect from
    two platforms disagreeing, and it fails on every platform rather than only
    on the ones that did not build the golden.
    """
    first = _tsv(tmp_path, locus, n=n, mixed=mixed, tag="first")
    second = _tsv(tmp_path, locus, n=n, mixed=mixed, tag="second")
    assert first == second, f"{name}: two runs of the same seed produced different bytes"


@pytest.mark.parametrize("name,locus,n,mixed", FIXTURES)
def test_output_matches_the_committed_golden(name, locus, n, mixed, tmp_path):
    """Cross-platform agreement.

    Passes on the platform that produced the golden and bites on the others,
    which is the point. A failure names the first differing line, so the report
    is precise about what diverged rather than just that something did.
    """
    golden_path = paths.golden(name)
    assert golden_path.is_file(), (
        f"{golden_path} is missing. Regenerate with "
        "`python .private/scripts/regenerate_golden_files.py`.")
    expected = golden_path.read_text(encoding="utf-8").splitlines()
    actual = _tsv(tmp_path, locus, n=n, mixed=mixed).splitlines()

    if expected == actual:
        return
    assert len(expected) == len(actual), (
        f"{name}: golden has {len(expected)} lines, this platform produced "
        f"{len(actual)}. If the output format changed intentionally, regenerate "
        "the goldens; otherwise this is a divergence.")
    for number, (want, got) in enumerate(zip(expected, actual), start=1):
        if want != got:
            column = next((i for i, (a, b) in enumerate(zip(want, got)) if a != b),
                          min(len(want), len(got)))
            pytest.fail(
                f"{name}: diverged from the golden at line {number}, character "
                f"{column}.\n  golden: ...{want[max(0, column - 30):column + 30]}...\n"
                f"  here:   ...{got[max(0, column - 30):column + 30]}...")


def test_every_committed_golden_is_read_by_this_module():
    """A fixture nothing reads is dead weight that looks load-bearing -- which
    is what all four of these were: generated by a script calling an API that
    no longer exists, never read by any test, and drifted to a 56-column schema
    the product had stopped producing."""
    on_disk = {path.name for path in paths.golden().glob("seed*.tsv")}
    checked = {name for name, _, _, _ in FIXTURES}
    assert on_disk == checked, (
        f"goldens nothing checks: {sorted(on_disk - checked)}; "
        f"checked but absent: {sorted(checked - on_disk)}")

#!/usr/bin/env python3
"""Regenerate the cross-platform reproducibility fixtures.

Run this when the AIRR output format changes on purpose -- a column added,
float precision adjusted. The checked-in files under ``tests/golden/`` then
become the new reference, and
``tests/acceptance/test_reproducibility.py`` asserts every CI platform
reproduces them byte for byte.

    python tools/regenerate_golden_files.py      # or: make goldens

The configuration lives in ``tests/support/golden.py``, shared with the test,
so the generator and the checker cannot disagree. The previous version of this
script called ``run_to_file`` and ``GenAIRR.ops``, neither of which exists any
more, and the test it named had never been written -- so the fixtures drifted to
a 56-column schema the product no longer produces.

It lives in ``tools/`` rather than in the ignored ``.private/`` tree because
the fixtures it produces are committed: a committed artifact with an
uncommitted producer cannot be regenerated by anyone else.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from tests.support.golden import every_fixture, write_reproducibility_tsv  # noqa: E402

GOLDEN_DIR = REPO_ROOT / "tests" / "golden"


def main() -> int:
    GOLDEN_DIR.mkdir(parents=True, exist_ok=True)
    for name, locus, n, mixed in every_fixture():
        out = write_reproducibility_tsv(GOLDEN_DIR / name, locus, n=n, mixed=mixed)
        print(f"  {out.relative_to(REPO_ROOT)}  ({out.stat().st_size} bytes)")
    print("\nCommit these. They are the reference every CI platform is checked against.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
